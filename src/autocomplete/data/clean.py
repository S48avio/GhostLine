"""Step 3: keep only real, hand-written Python 3, and stop any one package dominating.

Filters (in order; the stats say how many files each one removed):
    unreadable     not valid UTF-8
    too big        > 200 KB, or a line > 1,000 chars (data dumps, minified code)
    syntax error   ast.parse fails (Python 2, templates, broken files)
    empty          no statements (e.g. an empty __init__.py)
    generated      header says "auto-generated", "DO NOT EDIT", ...
    package cap    at most 300 files per package (random, seeded)

The output stores the code text itself: a frozen copy, so later steps don't
change if a venv is updated or deleted.

Usage:
    uv run python -m autocomplete.data.clean
"""

import ast
import json
import random
import re
import warnings
from collections import Counter, defaultdict
from multiprocessing import Pool
from pathlib import Path

from autocomplete import config

MAX_BYTES = 200_000
MAX_LINE = 1_000
PACKAGE_CAP = 300
GENERATED = re.compile(
    r"auto-?generated|do not edit|generated by|generated from|this file (is|was) generated|@generated",
    re.I,
)


def check(record: dict) -> tuple[str, dict]:
    """Return (status, record-with-code). Runs in a worker process."""
    try:
        code = Path(record["path"]).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return "unreadable", record
    if record["bytes"] > MAX_BYTES or max((len(line) for line in code.splitlines()), default=0) > MAX_LINE:
        return "too big", record
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")  # old code triggers SyntaxWarnings (e.g. "\d" in strings)
            tree = ast.parse(code)
    except (SyntaxError, ValueError):
        return "syntax error", record
    if not tree.body:
        return "empty", record
    if GENERATED.search("\n".join(code.splitlines()[:30])):
        return "generated", record
    return "ok", {**record, "code": code}


def main() -> None:
    records = [json.loads(line) for line in config.FILES.open()]
    stats: Counter[str] = Counter()
    generated_by_pkg: Counter[str] = Counter()
    by_package: dict[str, list[dict]] = defaultdict(list)

    with Pool(8) as pool:
        for status, rec in pool.imap_unordered(check, records, chunksize=200):
            stats[status] += 1
            if status == "generated":
                generated_by_pkg[rec["package"]] += 1
            if status == "ok":
                by_package[rec["package"]].append(rec)

    # Package cap. Your own code ("savio:*") is never capped: it's tiny and only used for testing.
    rng = random.Random(config.SEED)
    kept: list[dict] = []
    capped: Counter[str] = Counter()
    for pkg in sorted(by_package):
        files = sorted(by_package[pkg], key=lambda r: r["path"])  # sort first so the seed is reproducible
        if len(files) > PACKAGE_CAP and not pkg.startswith("savio:"):
            capped[pkg] = len(files) - PACKAGE_CAP
            files = rng.sample(files, PACKAGE_CAP)
        kept.extend(files)
    stats["package cap"] = sum(capped.values())
    stats["ok"] -= stats["package cap"]

    with config.CLEAN.open("w") as f:
        for rec in kept:
            f.write(json.dumps(rec) + "\n")

    print(f"{len(records):,} files in")
    for k in ("unreadable", "too big", "syntax error", "empty", "generated", "package cap", "ok"):
        print(f"  {k:13s} {stats[k]:>7,}")
    print(f"generated code, top packages: {generated_by_pkg.most_common(6)}")
    print(f"package cap hit, top packages: {capped.most_common(6)}")
    n_lines = sum(r["code"].count("\n") for r in kept)
    mb = sum(len(r["code"]) for r in kept) / 1e6
    print(f"wrote {len(kept):,} files ({len(by_package):,} packages, {n_lines / 1e6:.1f} M lines, {mb:.0f} MB) to {config.CLEAN}")


if __name__ == "__main__":
    main()
